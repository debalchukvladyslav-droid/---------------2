CREATE INDEX IF NOT EXISTS ai_learning_examples_review_idx
    ON public.ai_learning_examples(review_status, is_current, created_at DESC);
CREATE INDEX IF NOT EXISTS ai_learning_examples_user_trade_idx
    ON public.ai_learning_examples(user_id, trade_key, is_current);
CREATE INDEX IF NOT EXISTS ai_learning_examples_embedding_idx
    ON public.ai_learning_examples USING hnsw (embedding extensions.vector_cosine_ops)
    WHERE embedding IS NOT NULL AND review_status IN ('approved', 'corrected') AND is_current;

CREATE OR REPLACE FUNCTION public.match_ai_learning_examples(
    query_embedding extensions.vector(768),
    match_count INTEGER DEFAULT 5
)
RETURNS TABLE (id UUID, pattern_key TEXT, similarity DOUBLE PRECISION, source_snapshot JSONB, outcome JSONB)
LANGUAGE SQL STABLE SECURITY DEFINER SET search_path = public, extensions
AS $$
    SELECT e.id,
           COALESCE(e.reviewed_pattern_key, e.ai_pattern_key),
           1 - (e.embedding <=> query_embedding),
           e.source_snapshot,
           e.outcome
    FROM public.ai_learning_examples e
    WHERE e.embedding IS NOT NULL
      AND e.is_current
      AND e.review_status IN ('approved', 'corrected')
    ORDER BY e.embedding <=> query_embedding
    LIMIT LEAST(GREATEST(match_count, 1), 10);
$$;

